import { expect, test } from '@playwright/test';

test('Admin publica e paciente reserva, reabre o link, remarca e cancela', async ({ page, browser }, testInfo) => {
  test.skip(!process.env.E2E_PASSWORD, 'Use somente credencial temporária de sistema_dez_test.');
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const next = new Date(); next.setDate(next.getDate() + 1);
  const date = next.toLocaleDateString('en-CA', { timeZone: 'America/Fortaleza' });
  const weekday = new Date(`${date}T12:00:00-03:00`).getDay();
  await page.goto('/cadastros');
  await page.getByLabel('E-mail', { exact: true }).fill('admin-piloto@example.test');
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Cadastros e acessos' })).toBeVisible();
  await page.getByRole('tab', { name: 'Ofertas e horários' }).click();
  await page.getByLabel('Vínculo validado').selectOption({ label: 'CONSULTA PILOTO E2E · PROFISSIONAL PILOTO E2E · PARTICULAR PILOTO' });
  await page.getByLabel('Preço vigente de origem').selectOption({ label: 'R$ 150,00 · PRIVATE' });
  await page.getByRole('button', { name: 'Salvar oferta', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Escalas · CONSULTA PILOTO E2E' })).toBeVisible();
  await page.getByLabel('Dia da semana').selectOption(String(weekday));
  await page.getByLabel('Início da vigência').fill(date);
  await page.getByLabel('Hora inicial', { exact: true }).fill('08:00');
  await page.getByLabel('Hora final', { exact: true }).fill('10:00');
  await page.getByRole('button', { name: 'Adicionar escala' }).click();
  await expect(page.locator('.schedule-rule').filter({ hasText: '08:00–10:00' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Confirmar publicação online' })).toBeDisabled();
  await page.getByLabel('Publicar até').fill(date);
  await page.getByLabel('Conferi preço e escala e autorizo a oferta online.').check();
  await page.getByRole('button', { name: 'Confirmar publicação online' }).click();
  await expect(page.getByText(`Publicação autorizada até ${date}.`, { exact: false })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('publicacao-autorizada.png'), fullPage: true });

  const patientContext = await browser.newContext({ viewport: page.viewportSize()! });
  const patient = await patientContext.newPage();
  patient.on('pageerror', (error) => errors.push(error.message));
  const consoleErrors: string[] = [];
  patient.on('console', (message) => { if (['error', 'warning'].includes(message.type())) consoleErrors.push(message.text()); });
  await patient.goto('http://localhost:4176');
  await expect(patient).toHaveTitle(/DEZ/);
  await patient.getByRole('button', { name: /CONSULTA PILOTO E2E/ }).click();
  await expect(patient.getByLabel('Profissional, unidade e convênio')).toBeVisible();
  await patient.locator('.date-list button').first().click();
  await patient.locator('.slot-list button').filter({ hasText: '08:00' }).click();
  await patient.getByRole('button', { name: 'Continuar', exact: true }).click();
  await patient.getByLabel('Nome completo').fill('Paciente Publicação E2E');
  await patient.getByLabel('CPF', { exact: true }).fill('12345678909');
  await patient.getByLabel('WhatsApp', { exact: true }).fill('85999999999');
  await patient.getByLabel('Concordo com o uso dos meus dados', { exact: false }).check();
  await patient.getByRole('button', { name: 'Revisar agendamento' }).click();
  await patient.getByRole('button', { name: 'Confirmar agendamento', exact: true }).click();
  await expect(patient.getByRole('heading', { name: 'Tudo certo, Paciente!' })).toBeVisible();
  await expect(patient.getByLabel('Seu link privado')).toHaveValue(/#agendamento=.*&token=[a-f0-9]{64}$/);
  await patient.getByRole('button', { name: 'Gerenciar agendamento', exact: true }).click();
  await expect(patient.getByRole('heading', { name: 'Gerenciar agendamento' })).toBeVisible();
  await patient.reload();
  await expect(patient.getByRole('heading', { name: 'Gerenciar agendamento' })).toBeVisible();
  await patient.getByLabel('Novo horário').selectOption({ label: `${new Intl.DateTimeFormat('pt-BR', { dateStyle: 'short' }).format(next)}, 08:30 · 1 vaga(s)` });
  await patient.getByLabel('Motivo da alteração').fill('Teste de remarcação pelo paciente');
  await patient.getByLabel('Confirmo a alteração ou o cancelamento deste agendamento.').check();
  await patient.getByRole('button', { name: 'Confirmar remarcação' }).click();
  await expect(patient.getByRole('status')).toContainText('remarcado com sucesso');
  await expect(patient.locator('.receipt')).toContainText('08:30');
  await patient.screenshot({ path: testInfo.outputPath('paciente-remarcado.png'), fullPage: true });
  await patient.getByLabel('Confirmo a alteração ou o cancelamento deste agendamento.').check();
  await patient.getByRole('button', { name: 'Cancelar agendamento', exact: true }).click();
  await expect(patient.locator('.receipt')).toContainText('Cancelado');
  await expect(patient.getByLabel('Novo horário')).toHaveCount(0);
  expect(await patient.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await patient.screenshot({ path: testInfo.outputPath('paciente-cancelado.png'), fullPage: true });
  await page.getByRole('button', { name: 'Retirar do online' }).click();
  await expect(page.getByText('Oferta privada: disponível apenas para a equipe.')).toBeVisible();
  await patient.getByRole('button', { name: 'Voltar aos serviços' }).click();
  await patient.reload();
  await expect(patient.getByText('Nenhum serviço disponível online')).toBeVisible();
  expect(errors).toEqual([]);
  expect(consoleErrors).toEqual([]);
  await patientContext.close();
});
