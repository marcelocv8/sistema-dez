import { expect, test } from '@playwright/test';

test('piloto real: login, oferta, escala, reserva, remarcação e cancelamento', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_PASSWORD, 'Defina credencial temporária do ambiente sistema_dez_test.');
  const runtimeErrors: string[] = [];
  page.on('pageerror', (error) => runtimeErrors.push(error.message));
  page.on('console', (message) => {
    const url = message.location().url;
    if (message.text().includes('401 (Unauthorized)') && url.endsWith('/api/v1/me')) return;
    if (['error', 'warning'].includes(message.type())) runtimeErrors.push(`${message.text()} ${url}`);
  });
  const next = new Date(); next.setDate(next.getDate() + 1);
  const date = next.toLocaleDateString('en-CA', { timeZone: 'America/Fortaleza' });
  const weekday = new Date(`${date}T12:00:00-03:00`).getDay();
  await page.goto('/cadastros');
  await page.getByLabel('E-mail', { exact: true }).fill('admin-piloto@example.test');
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Cadastros e acessos' })).toBeVisible();
  await page.getByRole('tab', { name: 'Ofertas e horários' }).click();
  await page.getByLabel('Vínculo validado').selectOption({ label: 'CONSULTA PILOTO E2E · PROFISSIONAL PILOTO E2E · PARTICULAR PILOTO' });
  await page.getByLabel('Preço vigente de origem').selectOption({ label: 'R$ 150,00 · PRIVATE' });
  const offerResponse = page.waitForResponse((response) => response.url().endsWith('/team/service-offerings') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Salvar oferta', exact: true }).click();
  const offer = await (await offerResponse).json();
  expect(offer.data.online_enabled).toBe(false);
  await expect(page.getByRole('heading', { name: 'Escalas · CONSULTA PILOTO E2E' })).toBeVisible();
  await page.getByLabel('Dia da semana').selectOption(String(weekday));
  await page.getByLabel('Início da vigência').fill(date);
  await page.getByLabel('Hora inicial', { exact: true }).fill('08:00');
  await page.getByLabel('Hora final', { exact: true }).fill('10:00');
  const scaleResponse = page.waitForResponse((response) => response.url().endsWith('/schedule-windows') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Adicionar escala' }).click();
  expect((await scaleResponse).status()).toBe(201);
  await expect(page.locator('.schedule-rule').filter({ hasText: '08:00–10:00' })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath('oferta-escala.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await page.getByLabel('E-mail', { exact: true }).fill('recepcao-piloto@example.test');
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Cadastros e acessos' })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'Ofertas e horários' })).toHaveCount(0);
  await page.goto('/agenda');
  await page.getByRole('button', { name: 'Novo agendamento', exact: true }).click();
  await page.getByLabel('Oferta de atendimento').selectOption(offer.data.id);
  await page.getByLabel('Data do agendamento').fill(date);
  await page.getByLabel('Horário disponível').selectOption({ label: '08:00 · 1 vaga(s)' });
  await page.getByLabel('CPF do paciente').fill('123.456.789-09');
  await page.getByRole('button', { name: 'Localizar paciente' }).click();
  await expect(page.getByRole('status')).toContainText(/Paciente/);
  await page.getByLabel('Nome do paciente').fill('Paciente Piloto E2E');
  await page.getByLabel('Telefone do paciente').fill('85999999999');
  await page.getByLabel('Paciente informado sobre o uso dos dados para o agendamento.').check();
  await page.getByRole('button', { name: 'Confirmar agendamento interno' }).click();
  await expect(page.getByRole('heading', { name: 'Novo agendamento interno' })).not.toBeVisible();
  await page.getByRole('button', { name: 'Próximo dia', exact: true }).click();
  const confirmed = page.locator('.appointment--success').filter({ hasText: 'Paciente Piloto E2E' });
  await expect(confirmed).toBeVisible();
  await confirmed.click();
  await page.getByLabel('Horário disponível').selectOption({ label: '08:30 · 1 vaga(s)' });
  await page.getByLabel('Motivo da alteração ou cancelamento').fill('Teste de remarcação do piloto');
  await page.getByRole('button', { name: 'Remarcar agendamento', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Agendamento de Paciente Piloto E2E' })).not.toBeVisible();
  await expect(confirmed).toContainText('08:30');
  await page.getByLabel('Cancelado', { exact: true }).uncheck();
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await confirmed.evaluate((element) => { const card = element.getBoundingClientRect(); const row = element.parentElement!.getBoundingClientRect(); return card.bottom <= row.bottom && card.top >= row.top; })).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('agenda-remarcada.png'), fullPage: true });
  await confirmed.click();
  await page.getByLabel('Motivo da alteração ou cancelamento').fill('Encerramento do teste isolado');
  await page.getByRole('button', { name: 'Cancelar agendamento', exact: true }).click();
  await expect(confirmed).toHaveCount(0);
  expect(runtimeErrors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
